import 'dart:math';

/// Identifiant aléatoire (UUID v4) choisi par l'appareil pour un envoi
/// (alerte, publication, message) : un renvoi après une coupure réseau ne
/// crée pas de doublon côté serveur.
String newClientRef([Random? random]) {
  final r = random ?? Random.secure();
  final b = List<int>.generate(16, (_) => r.nextInt(256));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  String hex(int from, int to) => b
      .sublist(from, to)
      .map((x) => x.toRadixString(16).padLeft(2, '0'))
      .join();
  return '${hex(0, 4)}-${hex(4, 6)}-${hex(6, 8)}-${hex(8, 10)}-${hex(10, 16)}';
}
